//! Generation of data tables from an upstream Rufus checkout
//! (`cargo xtask gen-tables --upstream <path> [--check]`).
//!
//! Tables are generated rather than retyped so that they stay byte-for-byte
//! identical to upstream. The C headers are parsed as text; no C is compiled.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process::Command;

/// ms-sys MBR boot code tables used by `src/ms-sys/br.c` identification
/// functions: (header file, array names, `#define` names).
const MS_SYS_TABLES: &[(&str, &[&str], &[&str])] = &[
    ("mbr_dos.h", &["mbr_dos_0x0"], &[]),
    ("mbr_dos_f2.h", &["mbr_dos_f2_0x0"], &[]),
    ("mbr_95b.h", &["mbr_95b_0x0", "mbr_95b_0x0e0"], &[]),
    (
        "mbr_2000.h",
        &["mbr_2000_0x0"],
        &["MBR_2000_LANG_INDEP_LEN"],
    ),
    (
        "mbr_vista.h",
        &["mbr_vista_0x0"],
        &["MBR_VISTA_LANG_INDEP_LEN"],
    ),
    (
        "mbr_win7.h",
        &["mbr_win7_0x0"],
        &["MBR_WIN7_LANG_INDEP_LEN"],
    ),
    ("mbr_rufus.h", &["mbr_rufus_0x0"], &[]),
    ("mbr_syslinux.h", &["mbr_syslinux_0x0"], &[]),
    ("mbr_isolinux.h", &["mbr_isolinux_0x0"], &[]),
    ("mbr_reactos.h", &["mbr_reactos_0x0"], &[]),
    ("mbr_kolibri.h", &["mbr_kolibri_0x0"], &[]),
    ("mbr_grub.h", &["mbr_grub_0x0"], &[]),
    ("mbr_grub2.h", &["mbr_grub2_0x0"], &[]),
    ("mbr_zero.h", &["mbr_zero_0x0"], &[]),
];

pub fn run(root: &Path, upstream: &Path, check: bool) -> Result<(), String> {
    let source = Source::open(upstream)?;
    let outputs = [
        (
            "crates/ferrufus-core/src/image/ms_sys_tables.rs",
            generate_ms_sys(&source)?,
        ),
        (
            "crates/ferrufus-core/src/device/hdd_tables.rs",
            generate_hdd(&source)?,
        ),
    ];
    let mut stale = Vec::new();
    for (relative, content) in &outputs {
        let path = root.join(relative);
        if check {
            let current = fs::read_to_string(&path).unwrap_or_default();
            if current != *content {
                stale.push(*relative);
            }
        } else {
            fs::write(&path, content)
                .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
            println!("gen-tables: wrote {relative}");
        }
    }
    if stale.is_empty() {
        if check {
            println!("gen-tables: tables match {}", source.describe());
        }
        Ok(())
    } else {
        Err(format!(
            "tables differ from {}: {}",
            source.describe(),
            stale.join(", ")
        ))
    }
}

/// An upstream checkout and its identity.
struct Source<'a> {
    root: &'a Path,
    version: String,
    commit: String,
}

impl<'a> Source<'a> {
    fn open(root: &'a Path) -> Result<Self, String> {
        let configure = read(&root.join("configure.ac"))?;
        let version = configure
            .lines()
            .find_map(|line| line.strip_prefix("AC_INIT([rufus],"))
            .and_then(|rest| rest.trim().strip_prefix('['))
            .and_then(|rest| rest.split(']').next())
            .map(str::trim)
            .ok_or("configure.ac has no AC_INIT version")?
            .to_string();
        let output = Command::new("git")
            .args(["-C", &root.display().to_string(), "rev-parse", "HEAD"])
            .output()
            .map_err(|e| format!("cannot run git: {e}"))?;
        if !output.status.success() {
            return Err(format!("{} is not a git checkout", root.display()));
        }
        let commit = String::from_utf8_lossy(&output.stdout).trim().to_string();
        Ok(Self {
            root,
            version,
            commit,
        })
    }

    fn describe(&self) -> String {
        format!("pbatard/rufus {} (commit {})", self.version, self.commit)
    }

    fn header(&self, files: &str) -> String {
        format!(
            "// SPDX-License-Identifier: GPL-3.0-or-later\n\
             // @generated by `cargo xtask gen-tables` from {files}\n\
             // of {}. Do not edit by hand.\n",
            self.describe()
        )
    }

    fn read(&self, relative: &str) -> Result<String, String> {
        read(&self.root.join(relative))
    }
}

fn generate_ms_sys(source: &Source<'_>) -> Result<String, String> {
    let mut out = source.header("`src/ms-sys/inc/mbr_*.h`");
    out.push_str(
        "//\n\
         // Boot code of known master boot records, from ms-sys by Henrik Carlqvist\n\
         // (GPL-2.0-or-later) as shipped with Rufus. Used to identify MBRs the same\n\
         // way `src/ms-sys/br.c` does.\n",
    );
    for (header, arrays, defines) in MS_SYS_TABLES {
        let text = source.read(&format!("src/ms-sys/inc/{header}"))?;
        out.push('\n');
        let _ = writeln!(out, "// From `src/ms-sys/inc/{header}`.");
        for define in *defines {
            let value = parse_define(&text, define)
                .ok_or_else(|| format!("{header}: no #define {define}"))?;
            let _ = writeln!(out, "pub(crate) const {define}: usize = {value:#x};");
        }
        for array in *arrays {
            let bytes = parse_byte_array(&text, array)
                .ok_or_else(|| format!("{header}: no array {array}"))?;
            out.push_str(&format_byte_array(&array.to_uppercase(), &bytes));
        }
    }
    Ok(out)
}

fn generate_hdd(source: &Source<'_>) -> Result<String, String> {
    let text = source.read("src/hdd_vs_ufd.h")?;
    let mut out = source.header("`src/hdd_vs_ufd.h`");
    out.push_str(
        "//\n\
         // Hard drive versus flash drive scores, from Rufus (Copyright © 2013-2023 Pete\n\
         // Batard), based in part on smartmontools' drivedb.h (Copyright © 2003-11\n\
         // Philip Williams, Bruce Allen; © 2008-13 Christian Franke; GPL-2.0-or-later),\n\
         // the flashboot.ru iflash database and the Linux USB ID list. A positive\n\
         // score means hard drive, a negative one flash drive. Order is significant:\n\
         // `IsHDD()` stops scanning `str_score` at the first pattern longer than the\n\
         // device name, and the first matching VID and VID:PID entries win.\n",
    );

    let str_score = parse_struct_entries(&text, "str_score").ok_or("no str_score table")?;
    let str_adjust = parse_struct_entries(&text, "str_adjust").ok_or("no str_adjust table")?;
    let vid_score = parse_struct_entries(&text, "vid_score").ok_or("no vid_score table")?;
    let vidpid_score =
        parse_struct_entries(&text, "vidpid_score").ok_or("no vidpid_score table")?;

    out.push_str("\n/// `str_score[]`: model prefixes; `#` means one digit.\n");
    out.push_str("#[rustfmt::skip]\npub(crate) static STR_SCORE: &[(&str, i32)] = &[\n");
    for fields in &str_score {
        let [name, score] = fields.as_slice() else {
            return Err("bad str_score entry".into());
        };
        let _ = writeln!(out, "    ({name}, {}),", parse_int(score)?);
    }
    out.push_str("];\n");

    out.push_str("\n/// `str_adjust[]`: case-insensitive substrings, all applied.\n");
    out.push_str("#[rustfmt::skip]\npub(crate) static STR_ADJUST: &[(&str, i32)] = &[\n");
    for fields in &str_adjust {
        let [name, score] = fields.as_slice() else {
            return Err("bad str_adjust entry".into());
        };
        let _ = writeln!(out, "    ({name}, {}),", parse_int(score)?);
    }
    out.push_str("];\n");

    out.push_str("\n/// `vid_score[]`: USB vendor IDs.\n");
    out.push_str("#[rustfmt::skip]\npub(crate) static VID_SCORE: &[(u16, i32)] = &[\n");
    for fields in &vid_score {
        let [vid, score] = fields.as_slice() else {
            return Err("bad vid_score entry".into());
        };
        let _ = writeln!(
            out,
            "    ({:#06x}, {}),",
            parse_int(vid)?,
            parse_int(score)?
        );
    }
    out.push_str("];\n");

    out.push_str("\n/// `vidpid_score[]`: USB vendor and product IDs.\n");
    out.push_str("#[rustfmt::skip]\npub(crate) static VIDPID_SCORE: &[(u16, u16, i32)] = &[\n");
    for fields in &vidpid_score {
        let [vid, pid, score] = fields.as_slice() else {
            return Err("bad vidpid_score entry".into());
        };
        let _ = writeln!(
            out,
            "    ({:#06x}, {:#06x}, {}),",
            parse_int(vid)?,
            parse_int(pid)?,
            parse_int(score)?
        );
    }
    out.push_str("];\n");
    Ok(out)
}

/// Removes `/* */` and `//` comments (outside string literals).
fn strip_c_comments(text: &str) -> String {
    let chars: Vec<char> = text.chars().collect();
    let mut out = String::with_capacity(text.len());
    let mut i = 0;
    let mut in_string = false;
    while let Some(&c) = chars.get(i) {
        let next = chars.get(i + 1).copied();
        if in_string {
            out.push(c);
            if c == '\\' {
                if let Some(next) = next {
                    out.push(next);
                }
                i += 2;
                continue;
            }
            if c == '"' {
                in_string = false;
            }
            i += 1;
        } else if c == '"' {
            in_string = true;
            out.push(c);
            i += 1;
        } else if c == '/' && next == Some('*') {
            i += 2;
            while let Some(&c) = chars.get(i) {
                if c == '*' && chars.get(i + 1) == Some(&'/') {
                    i += 2;
                    break;
                }
                i += 1;
            }
            out.push(' ');
        } else if c == '/' && next == Some('/') {
            while let Some(&c) = chars.get(i) {
                if c == '\n' {
                    break;
                }
                i += 1;
            }
        } else {
            out.push(c);
            i += 1;
        }
    }
    out
}

/// The text between `{` and the matching `};` of the initializer of `name`.
fn initializer<'a>(text: &'a str, name: &str) -> Option<&'a str> {
    let declaration = format!("{name}[]");
    let start = text.find(&declaration)?;
    let rest = &text[start + declaration.len()..];
    let open = rest.find('{')?;
    let body = &rest[open + 1..];
    let close = body.find("};")?;
    Some(&body[..close])
}

fn parse_byte_array(text: &str, name: &str) -> Option<Vec<u8>> {
    let text = strip_c_comments(text);
    let body = initializer(&text, name)?;
    body.split(',')
        .map(str::trim)
        .filter(|token| !token.is_empty())
        .map(|token| {
            parse_int(token)
                .ok()
                .and_then(|value| u8::try_from(value).ok())
        })
        .collect()
}

/// Entries of a C array of structs: `{ a, b }, { c, d }` → `[[a, b], [c, d]]`,
/// with string literals kept as written (they are valid Rust literals).
fn parse_struct_entries(text: &str, name: &str) -> Option<Vec<Vec<String>>> {
    let text = strip_c_comments(text);
    let body = initializer(&text, name)?;
    let mut entries = Vec::new();
    let mut rest = body;
    while let Some(open) = rest.find('{') {
        let after = &rest[open + 1..];
        let close = after.find('}')?;
        let fields = after[..close]
            .split(',')
            .map(|field| field.trim().to_string())
            .collect();
        entries.push(fields);
        rest = &after[close + 1..];
    }
    Some(entries)
}

fn parse_define(text: &str, name: &str) -> Option<i64> {
    text.lines().find_map(|line| {
        let mut words = line.split_whitespace();
        (words.next() == Some("#define") && words.next() == Some(name))
            .then(|| words.next())
            .flatten()
            .and_then(|value| parse_int(value).ok())
    })
}

fn parse_int(token: &str) -> Result<i64, String> {
    let token = token.trim();
    let (negative, digits) = match token.strip_prefix('-') {
        Some(rest) => (true, rest),
        None => (false, token.strip_prefix('+').unwrap_or(token)),
    };
    let value = match digits
        .strip_prefix("0x")
        .or_else(|| digits.strip_prefix("0X"))
    {
        Some(hex) => i64::from_str_radix(hex, 16),
        None => digits.parse::<i64>(),
    }
    .map_err(|e| format!("bad integer `{token}`: {e}"))?;
    Ok(if negative { -value } else { value })
}

fn format_byte_array(name: &str, bytes: &[u8]) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "#[rustfmt::skip]\npub(crate) static {name}: [u8; {}] = [",
        bytes.len()
    );
    for chunk in bytes.chunks(12) {
        let line: Vec<String> = chunk.iter().map(|byte| format!("{byte:#04x}")).collect();
        let _ = writeln!(out, "    {},", line.join(", "));
    }
    out.push_str("];\n");
    out
}

fn read(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|e| format!("cannot read {}: {e}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn byte_arrays_are_parsed_with_comments() {
        let text = "/* header */\nunsigned char x_0x0[] = {\n  0x33, 0xc0, /* c */ 0x8e, // d\n  0xd0\n};\n";
        assert_eq!(
            parse_byte_array(text, "x_0x0"),
            Some(vec![0x33, 0xc0, 0x8e, 0xd0])
        );
    }

    #[test]
    fn struct_tables_are_parsed() {
        let text = "static t s[] = {\n\t{ \"IC#\", 10 },\t// c\n\t{ \"SSD\", +20 }\n};\n";
        let entries = parse_struct_entries(text, "s").unwrap();
        assert_eq!(entries, vec![vec!["\"IC#\"", "10"], vec!["\"SSD\"", "+20"]]);
        assert_eq!(parse_int("+20").unwrap(), 20);
        assert_eq!(parse_int("-15").unwrap(), -15);
        assert_eq!(parse_int("0x05e3").unwrap(), 0x05e3);
    }

    #[test]
    fn defines_are_parsed() {
        assert_eq!(
            parse_define(
                "#define MBR_WIN7_LANG_INDEP_LEN 0x163\n",
                "MBR_WIN7_LANG_INDEP_LEN"
            ),
            Some(0x163)
        );
    }
}
